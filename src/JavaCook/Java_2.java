public class Java_2 {
    /**
     * @TimeComplexity O(N) N is the max length of listNode l1 and l2
     * @SpaceComplexity O(1) exclude auxiliary space
     */
    public ListNode addTwoNumbers(ListNode l1, ListNode l2) {
        if (l1 == null) return l2;
        if (l2 == null) return l1;

        ListNode dummyHead = new ListNode(0);
        ListNode curr = dummyHead;
        int carry = 0;
        while (l1 != null || l2 != null || carry != 0) {
            int sum = carry;
            if (l1 != null) {
                sum += l1.val;
                l1 = l1.next;
            }

            if (l2 != null) {
                sum += l2.val;
                l2 = l2.next;
            }

            carry = sum / 10;

            ListNode node = new ListNode(sum % 10);
            curr.next = node;
            curr = node;
        }

        return dummyHead.next;
    }
}